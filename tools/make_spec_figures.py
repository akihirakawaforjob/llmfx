def series(pivots: list[tuple[int, float]], wiggle: float = 0.10) -> list[dict]:
    """`(足番号, 値段)` の列を通る足を作る。"""
    out: list[dict] = []
    n = pivots[-1][0] + 1
    seg = 0
    for i in range(n):
        while seg + 1 < len(pivots) - 1 and i >= pivots[seg + 1][0]:
            seg += 1
        (i0, p0), (i1, p1) = pivots[seg], pivots[seg + 1]
        f = 0.0 if i1 == i0 else (i - i0) / (i1 - i0)
        g = 0.0 if i1 == i0 else (i + 1 - i0) / (i1 - i0)
        o = p0 + (p1 - p0) * f
        c = p0 + (p1 - p0) * min(1.0, g)
        amp = abs(p1 - p0) / max(1, i1 - i0)
        w = (amp * wiggle + 0.012) * (1 + 0.5 * math.sin(i * 1.7))
        out.append(dict(
            o=round(o, 3),
            h=round(max(o, c) + abs(w) * (1.4 if i % 3 else 0.7), 3),
            l=round(min(o, c) - abs(w) * (0.8 if i % 2 else 1.5), 3),
            c=round(c, 3), t=""))
    for i, p in pivots:                      # 折り返しの値をきっちり通す
        if i < len(out):
            out[i]["h"] = round(max(out[i]["h"], p), 3)
            out[i]["l"] = round(min(out[i]["l"], p), 3)
    return out


