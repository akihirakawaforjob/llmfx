"""仕様の図で使うローソク足を、折り返し(ピボット)の並びから作る.

**構造を先に決めて、そこを通る足を作る。**仕様の話は「どこで折り返した
か」だけで決まるので、そこを直接指定できる形にしておく。乱数は使わない
(毎回同じ図が出る)。

スクラッチパッドへ置くと、コンテナが巻き戻るたびに図の作り方ごと消える
(実際に 6 回消えた)。**リポジトリに入れておくこと。**

    python tools/make_spec_figures.py docs/handoff/spec-figures.json
"""

