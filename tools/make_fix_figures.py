"""帯の手前でしか入らない / 推進波の起点はどこか、の模式図を作る.

利用者の指摘(2026-09-14、負けの図を見て):
  「帯に対して向かう様に売りに入っている。抵抗帯の抵抗帯力を信じて
    買いに入るべき」「買い側でも発動しない様に」
  「機関投資家の守りたいポイントは、大きいローソク足の付け根部分な
    はずだし、そこに指値を置いた方が良い」

    python tools/make_fix_figures.py docs/handoff/fix-figures.json
"""

from __future__ import annotations

import json
import sys

from make_spec_figures import series

ATR = 0.10


def build() -> dict:
    fig: dict = {}

    # --- 直し方(売り)。帯を上抜けても、注文は帯の手前に留める ---------
    fig["near_sell"] = dict(
        candles=series([(0, 99.60), (6, 99.86), (10, 99.78), (15, 100.18),
                        (19, 100.06), (24, 100.22), (30, 99.72), (36, 99.44)],
                       wiggle=0.14),
        band=100.00, atr=ATR,
        keep=99.90,        # 帯の手前に留めた注文(これが正)
        drift=100.06,      # いまの実装が置き直してしまう水準(誤)
        arm_at=12, fill_at=28,
        stop=100.15,
    )

    # --- 直し方(買い)。帯を下抜けても、注文は帯の手前に留める ---------
    fig["near_buy"] = dict(
        candles=series([(0, 100.40), (6, 100.14), (10, 100.22), (15, 99.82),
                        (19, 99.94), (24, 99.78), (30, 100.28), (36, 100.56)],
                       wiggle=0.14),
        band=100.00, atr=ATR,
        keep=100.10,       # 帯の手前に留めた注文(これが正)
        drift=99.94,       # いまの実装が置き直してしまう水準(誤)
        arm_at=12, fill_at=28,
        stop=99.85,
    )

    # --- 推進波と調整波の区別。利用者の定義:
    #     「推進波 = 高値1・安値0 のような、調整波じゃない方の波」
    fig["impulse"] = dict(
        candles=series([(0, 99.88), (5, 100.06), (9, 99.96), (14, 100.46),
                        (19, 100.30), (25, 100.86), (30, 100.68),
                        (37, 101.22)], wiggle=0.11),
        atr=ATR,
        swings=[(0, 99.88, "安値0", "low"), (5, 100.06, "高値0", "high"),
                (9, 99.96, "安値1", "low"), (14, 100.46, "高値1", "high"),
                (19, 100.30, "安値2", "low"), (25, 100.86, "高値2", "high"),
                (30, 100.68, "安値3", "low")],
        # 推進波(トレンド方向)= 安値 → 高値
        push=[(9, 99.96, 14, 100.46), (19, 100.30, 25, 100.86)],
        # 調整波 = 高値 → 安値
        pull=[(14, 100.46, 19, 100.30), (25, 100.86, 30, 100.68)],
        last_push=0.56,      # 直近の推進波 100.86 - 100.30
    )

    # --- 損切りは、指値の位置から 直近の推進波 1 本分 外へ ---------------
    fig["wavestop"] = dict(
        candles=series([(0, 100.44), (5, 100.18), (10, 100.30), (16, 99.96),
                        (21, 100.12), (27, 99.70), (34, 99.40)], wiggle=0.12),
        band=100.50, atr=ATR,
        entry=100.12, entry_at=23,
        wave=0.34,           # 直近の推進波(100.30 → 99.96)
        stop=100.46,         # 指値 + 推進波 1 本分
        t1=99.78,            # 推進波 1 本分 進んだところ
        t2=99.44,            # 2 本分 = リスクリワード 2 対 1
        swings=[(5, 100.18, "高値a", "high"), (10, 100.30, "戻り", "high"),
                (16, 99.96, "安値a", "low"), (21, 100.12, "戻り", "high")],
    )

    return fig


if __name__ == "__main__":
    dst = sys.argv[1] if len(sys.argv) > 1 else "docs/handoff/fix-figures.json"
    fig = build()
    json.dump(fig, open(dst, "w"), ensure_ascii=False)
    for k, v in fig.items():
        cs = v["candles"]
        print(f"{k:<10}{len(cs):>4} 本  {min(c['l'] for c in cs):.2f}"
              f" 〜 {max(c['h'] for c in cs):.2f}")
